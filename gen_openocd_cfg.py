"""Generate OpenOCD configuration and synchronize VS Code tasks."""
import json
import os
import re
import glob

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
TASKS_PATH = os.path.join(SCRIPT_DIR, ".vscode", "tasks.json")
OPENOCD_TASK_LABELS = {
    "Flash (flash & reset, then exit OpenOCD)",
    "Build & Flash",
    "Start OpenOCD",
}


def find_ioc():
    """Find the .ioc file in the project root."""
    ioc_files = glob.glob(os.path.join(SCRIPT_DIR, "*.ioc"))
    if not ioc_files:
        print("[ERROR] No .ioc file found in project root!")
        return None
    return ioc_files[0]


def parse_family(ioc_path):
    """Parse Mcu.Family or Mcu.CPN from .ioc file."""
    with open(ioc_path, "r", encoding="utf-8") as f:
        content = f.read()

    family_match = re.search(r"Mcu\.Family=(\S+)", content)
    cpn_match = re.search(r"Mcu\.CPN=(\S+)", content)

    family = family_match.group(1) if family_match else None
    cpn = cpn_match.group(1) if cpn_match else None

    if not family and cpn:
        m = re.match(r"STM32(\w)\d+", cpn)
        if m:
            family = f"STM32{m.group(1)}"

    return family, cpn


FAMILY_TO_TARGET = {
    "STM32C0": "stm32c0x.cfg",
    "STM32C5": "stm32c5x.cfg",
    "STM32F0": "stm32f0x.cfg",
    "STM32F1": "stm32f1x.cfg",
    "STM32F2": "stm32f2x.cfg",
    "STM32F3": "stm32f3x.cfg",
    "STM32F4": "stm32f4x.cfg",
    "STM32F7": "stm32f7x.cfg",
    "STM32G0": "stm32g0x.cfg",
    "STM32G4": "stm32g4x.cfg",
    "STM32G5": "stm32g5x.cfg",
    "STM32H5": "stm32h5x.cfg",
    "STM32H7": "stm32h7x.cfg",
    "STM32L0": "stm32l0x.cfg",
    "STM32L1": "stm32l1x.cfg",
    "STM32L4": "stm32l4x.cfg",
    "STM32L5": "stm32l5x.cfg",
    "STM32N6": "stm32n6x.cfg",
    "STM32U0": "stm32u0x.cfg",
    "STM32U3": "stm32u3x.cfg",
    "STM32U5": "stm32u5x.cfg",
    "STM32WB": "stm32wbx.cfg",
    "STM32WL": "stm32wlx.cfg",
}


def _cpn_override(cpn):
    """Use full chip model to detect sub-variants that need a different target cfg."""
    if not cpn:
        return None
    overrides = {
        # L4+ 系列 (STM32L4R/S/P5)
        r"STM32L4[RSP]": "stm32l4plusx.cfg",
        # WB 子系列
        r"STM32WB0": "stm32wb0x.cfg",
        r"STM32WBA": "stm32wbax.cfg",
        # WL 子系列
        r"STM32WL3": "stm32wl3x.cfg",
        r"STM32WL4": "stm32wl4x.cfg",
    }
    for pattern, target in overrides.items():
        if re.match(pattern, cpn, re.IGNORECASE):
            return target
    return None


def get_target(family, cpn=None):
    """Map STM32 family to OpenOCD target config file."""
    override = _cpn_override(cpn)
    if override:
        return override
    if not family:
        return None
    for key, target in FAMILY_TO_TARGET.items():
        if family.upper() == key.upper():
            return target
    return None


def generate_cfg(family, cpn, target):
    """Write openocd.cfg."""
    cfg_path = os.path.join(SCRIPT_DIR, "openocd.cfg")
    with open(cfg_path, "w", encoding="utf-8") as f:
        f.write(f"# OpenOCD config - {cpn or family}\n")
        f.write("# Debugger: ST-LINK DAP (V2/V2-1/V3)\n")
        f.write("# Auto-generated by gen_openocd_cfg.py\n")
        f.write("\n")
        f.write("source [find interface/stlink-dap.cfg]\n")
        f.write("transport select dapdirect_swd\n")
        f.write("\n")
        f.write("set ENABLE_LOW_POWER 1\n")
        f.write(f"source [find target/{target}]\n")
        f.write("\n")
        f.write("# Use Cortex-M SYSRESETREQ so flashing also works without an NRST wire.\n")
        f.write("reset_config none\n")
        f.write("adapter speed 4000\n")
    print(f"[OK] Generated: {cfg_path}")
    print(f"     Chip: {cpn} (Family: {family})")
    print(f"     Target: {target}")


def detect_project_name(ioc_path):
    """Detect the ELF target name from CMakeLists.txt, then fall back to .ioc."""
    cmake_path = os.path.join(SCRIPT_DIR, "CMakeLists.txt")
    if os.path.exists(cmake_path):
        with open(cmake_path, "r", encoding="utf-8") as f:
            content = f.read()

        match = re.search(
            r"set\s*\(\s*CMAKE_PROJECT_NAME\s+(?:\"([^\"]+)\"|([^\s\)]+))",
            content,
            re.IGNORECASE,
        )
        if match:
            name = match.group(1) or match.group(2)
            if name and "$" not in name:
                return name

        match = re.search(
            r"project\s*\(\s*([A-Za-z0-9_.+-]+)", content, re.IGNORECASE
        )
        if match:
            return match.group(1)

    return os.path.splitext(os.path.basename(ioc_path))[0]


def update_tasks(project_name):
    """Apply the top-level path configuration and detected ELF name to tasks.json."""
    if not os.path.exists(TASKS_PATH):
        print(f"[ERROR] VS Code tasks file not found: {TASKS_PATH}")
        return False

    with open(TASKS_PATH, "r", encoding="utf-8-sig") as f:
        # tasks.json is JSONC. Our comments occupy complete lines, so remove
        # those lines before passing the content to Python's JSON parser.
        json_text = "".join(
            line for line in f if not line.lstrip().startswith("//")
        )
        data = json.loads(json_text)

    openocd_exe = data.get("_PATH_OCD_EXE")
    openocd_scripts = data.get("_PATH_OCD_SCRIPTS")
    if not openocd_exe or not openocd_scripts:
        print("[ERROR] Set _PATH_OCD_EXE and _PATH_OCD_SCRIPTS in tasks.json.")
        return False

    # Forward slashes are safe in Windows command lines and OpenOCD Tcl.
    openocd_exe = openocd_exe.replace("\\", "/")
    openocd_scripts = openocd_scripts.replace("\\", "/")
    data["_PATH_OCD_EXE"] = openocd_exe
    data["_PATH_OCD_SCRIPTS"] = openocd_scripts

    updated = 0
    for task in data.get("tasks", []):
        if task.get("label") not in OPENOCD_TASK_LABELS:
            continue

        task["command"] = openocd_exe
        args = task.get("args", [])
        for index, arg in enumerate(args):
            if arg == "-s" and index + 1 < len(args):
                args[index + 1] = openocd_scripts
            elif isinstance(arg, str) and arg.startswith("program "):
                args[index] = (
                    f"program build/Debug/{project_name}.elf verify reset exit"
                )
        updated += 1

    # Remove obsolete pseudo-comment fields from older versions.
    for key in (
        "_PATH_CONFIG",
        "_PATH_OCD_EXE_NOTE",
        "_PATH_OCD_SCRIPTS_NOTE",
        "_AUTO_CONFIG_NOTE",
    ):
        data.pop(key, None)

    output_lines = json.dumps(data, ensure_ascii=False, indent=4).splitlines()
    output = []
    for line in output_lines:
        stripped = line.lstrip()
        if stripped.startswith('"_PATH_OCD_EXE"'):
            output.append(
                "    // ==================== 换电脑时只需修改下面两项 ===================="
            )
            output.append("    // 1. 修改为新电脑上 openocd.exe 的完整路径。")
        elif stripped.startswith('"_PATH_OCD_SCRIPTS"'):
            output.append(
                "    // 2. 修改为新电脑上 OpenOCD st_scripts 文件夹的完整路径。"
            )
        elif stripped.startswith('"tasks"'):
            output.append(
                "    // 修改完成后运行 Generate openocd.cfg；下面任务中的路径和 ELF 文件名会自动同步，请勿逐项修改。"
            )
        output.append(line)

    with open(TASKS_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(output) + "\n")

    print(f"[OK] Updated: {TASKS_PATH}")
    print(f"     Project/ELF: {project_name} -> build/Debug/{project_name}.elf")
    print(f"     OpenOCD tasks updated: {updated}")

    paths_ok = True
    if not os.path.isfile(openocd_exe):
        print("[ERROR] _PATH_OCD_EXE does not point to an existing file.")
        paths_ok = False
    if not os.path.isdir(openocd_scripts):
        print("[ERROR] _PATH_OCD_SCRIPTS does not point to an existing directory.")
        paths_ok = False
    if not paths_ok:
        print("        Edit only the two _PATH_OCD_* values at the top of tasks.json.")
    return paths_ok


def main():
    print("=== STM32 OpenOCD Config Generator ===\n")

    ioc_path = find_ioc()
    if not ioc_path:
        return 1

    family, cpn = parse_family(ioc_path)
    print(f"  IOC file : {os.path.basename(ioc_path)}")
    print(f"  Chip     : {cpn}")
    print(f"  Family   : {family}")

    target = get_target(family, cpn)
    if not target:
        print(f"\n[ERROR] Unknown family '{family}'!")
        print("Supported families:")
        for k in sorted(FAMILY_TO_TARGET.keys()):
            print(f"  {k}")
        return 1

    project_name = detect_project_name(ioc_path)
    print(f"  Project  : {project_name}")

    generate_cfg(family, cpn, target)
    return 0 if update_tasks(project_name) else 1


if __name__ == "__main__":
    exit(main())
